-- Run this file in the Supabase SQL Editor.
-- This version uses a database-backed custom login with name + password,
-- so there is no email authentication dependency on auth.users.

create table public.student_profiles (
    id bigint generated by default as identity primary key,
    admission_number text,
    register_number text,
    full_name text not null unique,
    password text not null,
    date_of_birth date,
    department text,
    batch text,
    college text,
    email text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.semester_results (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.student_profiles(id) on delete cascade,
    semester integer not null check (semester between 1 and 8),
    semester_gpa numeric(4, 2) not null check (semester_gpa between 0 and 10),
    overall_gpa numeric(4, 2) not null check (overall_gpa between 0 and 10),
    total_credits numeric(5, 2) not null default 0,
    courses jsonb not null default '[]'::jsonb,
    updated_at timestamptz not null default now(),
    unique (student_id, semester)
);

alter table public.student_profiles disable row level security;
alter table public.semester_results disable row level security;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger student_profiles_updated_at
before update on public.student_profiles
for each row execute procedure public.set_updated_at();

create trigger semester_results_updated_at
before update on public.semester_results
for each row execute procedure public.set_updated_at();
